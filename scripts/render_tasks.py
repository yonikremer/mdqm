"""Validate the backlog and render tasks.json + TASKS.md.   python scripts/render_tasks.py"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from tasks_def import LANES, T

ROOT = Path(__file__).resolve().parent.parent


def validate_and_wave(tasks):
    by = {t["id"]: t for t in tasks}
    assert len(by) == len(tasks), "duplicate ids"
    for t in tasks:
        for d in t["depends_on"]:
            assert d in by, f"{t['id']} depends on unknown {d}"
        assert t["acceptance"] and t["test"], t["id"]
        for d in t["depends_on"]:
            assert by[d]["priority"] <= t["priority"], (
                f"{t['id']} ({t['priority']}) depends on lower-priority {d}"
            )
    wave: dict[str, int] = {}
    visiting: set[str] = set()

    def w(i):
        if i in wave:
            return wave[i]
        assert i not in visiting, f"cycle at {i}"
        visiting.add(i)
        wave[i] = 1 + max([w(d) for d in by[i]["depends_on"]], default=-1)
        visiting.discard(i)
        return wave[i]

    for i in by:
        w(i)
    for t in tasks:
        t["wave"] = wave[t["id"]]
    return by


def main():
    validate_and_wave(T)
    (ROOT / "tasks.json").write_text(
        json.dumps({"lanes": LANES, "tasks": T}, indent=1, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    waves: dict[int, list[dict]] = {}
    for t in T:
        waves.setdefault(t["wave"], []).append(t)
    p0 = [t for t in T if t["priority"] == "P0"]
    out = [
        "# TASKS: ordered backlog for autonomous agents",
        "",
        "<!-- GENERATED by scripts/render_tasks.py from scripts/tasks_def.py. Do not edit by hand. -->",
        "",
        "Read `AGENTS.md` first (rules, protocol, conventions). `docs/DESIGN.md` is the design. "
        "A task is **done** when `progress/<ID>.md` with `status: done` is on `main`. "
        "Pick work with `python scripts/next_tasks.py ready --priority P0,P1`.",
        "",
        "## How to read this",
        "",
        "- **Wave** = earliest round a task can start if all its dependencies are done. Tasks in the same wave touch "
        "disjoint files (see `owns`) and **can run in parallel**.",
        "- **Priority**: P0 = the MVP slice we want working by morning; P1 = valuable, do after P0; P2 = stretch / later.",
        "- **Phase**: `0` = discovery tooling, `MVP` = start of phase 1, `later` = after the MVP slice.",
        "- `Test command` is the exact command that must pass. Integration commands use `--require-services` "
        "(fail instead of skip) and need `python scripts/dev.py up <profile>` first.",
        "",
        "## Parallel waves (overview)",
        "",
        "| Wave | Tasks that can run in parallel |",
        "|---|---|",
    ]
    for k in sorted(waves):
        out.append(
            f"| {k} | "
            + ", ".join(f"{t['id']}{'' if t['priority'] == 'P0' else '*'}" for t in waves[k])
            + " |"
        )
    out += [
        "",
        "`*` = not P0.",
        "",
        f"**{len(T)} tasks, {len(p0)} of them P0.** Longest dependency chain: {max(waves) + 1} waves.",
        "",
        "## Dependency table",
        "",
        "| ID | Wave | Pri | Phase | Depends on | Title |",
        "|---|---|---|---|---|---|",
    ]
    for t in sorted(T, key=lambda t: (t["wave"], t["id"])):
        out.append(
            f"| {t['id']} | {t['wave']} | {t['priority']} | {t['phase']} | "
            f"{', '.join(t['depends_on']) or '-'} | {t['title']} |"
        )
    out.append("")
    for lane, name in LANES.items():
        out += [f"## Lane {lane}: {name}", ""]
        for t in [x for x in T if x["lane"] == lane]:
            par = [o["id"] for o in T if o["wave"] == t["wave"] and o["id"] != t["id"]]
            out += [
                f"### {t['id']}: {t['title']}",
                "",
                f"- **Phase** {t['phase']} | **Priority** {t['priority']} | **Wave** {t['wave']} | "
                f"**Depends on** {', '.join(t['depends_on']) or 'none'}",
                "- **Owns (files you may create/edit)**: " + ", ".join(f"`{o}`" for o in t["owns"]),
                f"- **Same wave (can run in parallel)**: {', '.join(par) if par else 'none'}",
                "",
                t["description"],
                "",
                "**Acceptance criteria**",
                "",
            ]
            out += [f"- [ ] {a}" for a in t["acceptance"]]
            out += ["", "**Test command**", "", "```", t["test"], "```", ""]
            if t["notes"]:
                out += [f"> Note: {t['notes']}", ""]
    (ROOT / "TASKS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(T)} tasks, {max(waves) + 1} waves, {len(p0)} P0")


if __name__ == "__main__":
    main()
